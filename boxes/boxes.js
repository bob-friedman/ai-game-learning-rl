const VIEWPORT_SCALE = 0.8;
const MIN_TILE = 8;
const MAX_TILE = 60;
function computeTileSize(boardW, boardH) {
  const vw = document.documentElement.clientWidth;
  const vh = document.documentElement.clientHeight;

  const topbarEl = document.getElementById('topbar');
  const dpadEl   = document.getElementById('dpad');
  const topbarH  = topbarEl ? topbarEl.getBoundingClientRect().height : 40;
  const dpadH    = (dpadEl && dpadEl.classList.contains('dpad-visible'))
                     ? dpadEl.getBoundingClientRect().height : 0;

  const containerPad = 32;
  const gapAboveBoard = 12;
  const gapBelowBoard = dpadH > 0 ? 12 : 0;
  const topbarMargin  = 4;

  const overhead = containerPad + topbarH + topbarMargin + gapAboveBoard + gapBelowBoard + dpadH;

  const availW = vw  * VIEWPORT_SCALE;
  const availH = vh  - overhead;
  const byW    = Math.floor(availW / boardW);
  const byH    = Math.floor(availH / boardH);
  return Math.min(MAX_TILE, Math.max(MIN_TILE, Math.min(byW, byH)));
}
