function parseSokobanLevels(text) {
    const lines = text.replace(/\r/g, '').split('\n');
    const result = [];
    let currentName = '';
    let currentMap  = [];
    const commit = () => { if (currentMap.length > 0) result.push({ name: currentName || `Level ${result.length + 1}`, map: currentMap }); };
    for (const line of lines) {
        const trimmed = line.trim();
        if (trimmed.startsWith(';')) { commit(); currentName = trimmed.substring(1).trim(); currentMap = []; }
        else if (trimmed.length > 0) currentMap.push(line);
    }
    commit();
    return result;
}
function parseLevelMap(mapLines) {
    const h = mapLines.length;
    const w = Math.max(...mapLines.map(l => l.length));
    const b = []; const boxList = []; const goalsList = []; let pl = null;
    for (let y = 0; y < h; y++) {
        b[y] = [];
        const row = mapLines[y] || '';
        const trimmed = row.trim();
        if (trimmed.length === 0) { for (let x = 0; x < w; x++) b[y][x] = '#'; continue; }
        const firstIdx = row.indexOf(trimmed);
        const lastIdx  = firstIdx + trimmed.length - 1;
        for (let x = 0; x < w; x++) {
            if (x < firstIdx || x > lastIdx) { b[y][x] = '#'; continue; }
            const ch = row[x]; b[y][x] = (ch === '#') ? '#' : ' ';
            switch (ch) {
                case '@': pl = { x, y }; break;
                case '$': boxList.push({ x, y }); break;
                case '.': goalsList.push({ x, y }); break;
                case '+': pl = { x, y }; goalsList.push({ x, y }); break;
                case '*': boxList.push({ x, y }); goalsList.push({ x, y }); break;
            }
        }
    }
    return { board: b, boxes: boxList, goals: goalsList, player: pl, width: w, height: h };
}
function boxAt(x, y)   { return boxes.find(b => b.x === x && b.y === y); }
function isWall(x, y)  { return (y < 0 || y >= board.length || x < 0 || x >= (board[y] || []).length || board[y][x] === '#'); }
function isGoalAt(x, y){ return goals.some(g => g.x === x && g.y === y); }
function deepCopy() { return { player: { x: player.x, y: player.y }, boxes: boxes.map(b => ({ x: b.x, y: b.y })) }; }
function restoreUndo(state) {
    player.x = state.player.x; player.y = state.player.y;
    boxes.forEach((b, i) => { b.x = state.boxes[i].x; b.y = state.boxes[i].y; });
}
function pushUndo() { undoStack.push(deepCopy()); if (undoStack.length > 200) undoStack.shift(); }
function undoMove()  { if (!undoStack.length) return; restoreUndo(undoStack.pop()); if (moves > 0) moves--; renderBoard(); }
function tryMove(dx, dy) {
    const nx = player.x + dx, ny = player.y + dy;
    if (isWall(nx, ny)) return;
    const targetBox = boxAt(nx, ny);
    if (targetBox) {
        const bx = targetBox.x + dx, by = targetBox.y + dy;
        if (isWall(bx, by) || boxAt(bx, by)) return;
        pushUndo();
        targetBox.x = bx; targetBox.y = by;
    } else {
        pushUndo();
    }
    player.x = nx; player.y = ny;
    moves++;
    renderBoard();
    if (isLevelComplete()) setTimeout(() => loadLevel((currentLevelIndex + 1) % levels.length), 600);
}
function isLevelComplete() {
    return goals.length > 0 && boxes.every(b => isGoalAt(b.x, b.y));
}
function getTileClass(x, y) {
    const onGoal = isGoalAt(x, y);
    const box    = boxAt(x, y);
    if (box)             return onGoal ? 'box-on-goal' : 'box';
    if (isWall(x, y))    return 'wall';
    if (onGoal)          return 'goal';
    return 'floor';
}
function renderBoard() {
    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            const el = tileElements[y]?.[x];
            if (!el) continue;
            const isPlayerHere = (player.x === x && player.y === y);
            const cls = isPlayerHere
                ? (isGoalAt(x, y) ? 'player-on-goal' : 'floor')
                : getTileClass(x, y);
            el.className = 'tile' + (cls ? ' ' + cls : '');
        }
    }
    const sprite = document.getElementById('player-sprite');
    if (sprite) {
        const tileSize = parseInt(getComputedStyle(document.documentElement).getPropertyValue('--tile-size'));
        sprite.style.transform = `translate(${player.x * tileSize}px, ${player.y * tileSize}px)`;
    }
}
function buildBoard() {
    gameBoard.innerHTML = '';
    tileElements = [];
    gameBoard.style.gridTemplateColumns = `repeat(${width}, var(--tile-size))`;
    for (let y = 0; y < height; y++) {
        tileElements[y] = [];
        for (let x = 0; x < width; x++) {
            const el = document.createElement('span');
            el.className = 'tile';
            const inner = document.createElement('span');
            el.appendChild(inner);
            el.style.gridColumn = `${x + 1}`;
            el.style.gridRow    = `${y + 1}`;
            gameBoard.appendChild(el);
            tileElements[y][x] = el;
        }
    }
    const sprite = document.createElement('div');
    sprite.id = 'player-sprite';
    gameBoard.appendChild(sprite);
    adjustTileSize();
    renderBoard();
}
function adjustTileSize() {
    const newSize = computeTileSize(width, height);
    document.documentElement.style.setProperty('--tile-size', `${newSize}px`);
}
