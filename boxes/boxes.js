function loadLevel(index) {
    if (!levels || !levels[index]) return;
    currentLevelIndex = index;
    try {
        localStorage.setItem('boxes_lastSetIndex',   currentSetIndex);
        localStorage.setItem('boxes_lastLevelIndex', index);
    } catch (e) {}
    const parsed = parseLevelMap(levels[index].map);
    board  = parsed.board;
    boxes  = parsed.boxes;
    goals  = parsed.goals;
    player = parsed.player || { x: 0, y: 0 };
    width  = parsed.width;
    height = parsed.height;
    undoStack = []; moves = 0;
    if (levelSelect) levelSelect.value = String(index);
    buildBoard();
}
function loadLevelSet(setIndex, startingLevel = 0) {
    if (!levelSets[setIndex]) return;
    currentSetIndex = setIndex;
    const levelText = INTERNAL_LEVEL_DATA[levelSets[setIndex].file];
    if (levelText) {
        levels = parseSokobanLevels(levelText);
    } else {
        levels = [{ name: 'Error: Load Failed', map: ['#####', '#.@$#', '#...#', '#####'] }];
    }
    populateLevelSelect();
    loadLevel(startingLevel);
}
window.addEventListener('keydown', e => {
    const k = e.key.toLowerCase();
    if      (k === 'arrowup'    || k === 'w') { e.preventDefault(); tryMove(0, -1); }
    else if (k === 'arrowdown'  || k === 's') { e.preventDefault(); tryMove(0,  1); }
    else if (k === 'arrowleft'  || k === 'a') { e.preventDefault(); tryMove(-1, 0); }
    else if (k === 'arrowright' || k === 'd') { e.preventDefault(); tryMove( 1, 0); }
    else if (k === 'u' || k === 'z')          undoMove();
    else if (k === 'r' && confirm('Reset?'))   loadLevel(currentLevelIndex);
});
